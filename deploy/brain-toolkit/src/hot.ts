import type { Entry } from "./scan.js";

const MAX_WORDS = 700;

function countWords(text: string): number {
  return text.trim().split(/\s+/).filter(Boolean).length;
}

/**
 * Build memory/hot.md — a compact (<700 word) top-of-session warm cache.
 * Identity first, then active projects, then conventions/feedback. Deterministic.
 */
export function buildHot(entries: Entry[]): string {
  const valid = entries.filter((e) => e.data !== null);
  const by = (b: string) =>
    valid
      .filter((e) => e.bucket === b)
      .sort((a, b2) => a.fileSlug.localeCompare(b2.fileSlug));

  const parts: string[] = [
    "# Hot Cache",
    "<!-- GENERATED by tools/brain (`npm run hot`). Top-of-session warm context; do not hand-edit. -->",
  ];

  const users = by("user");
  if (users.length > 0) {
    parts.push(
      "## Identity\n" +
        users.map((e) => `- ${e.data!.description}`).join("\n"),
    );
  }

  const projects = by("project");
  if (projects.length > 0) {
    parts.push(
      "## Active Projects\n" +
        projects.map((e) => `- **${e.data!.name}** — ${e.data!.description}`).join("\n"),
    );
  }

  const feedback = by("feedback");
  if (feedback.length > 0) {
    parts.push(
      "## Conventions & Feedback\n" +
        feedback.map((e) => `- **${e.data!.name}** — ${e.data!.description}`).join("\n"),
    );
  }

  let out = parts.join("\n\n") + "\n";

  // Hard word cap — trim trailing feedback lines if we somehow exceed the budget.
  if (countWords(out) > MAX_WORDS) {
    out =
      parts.slice(0, -1).join("\n\n") +
      "\n\n_(feedback list trimmed to keep hot.md under " +
      MAX_WORDS +
      " words — see MEMORY.md)_\n";
  }

  return out;
}
